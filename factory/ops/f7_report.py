"""f7_report.py — F7: the operating envelope of the v1 and v2 cells, as a figure and a report section (2026-11-03; discipline 15). Reads factory/ops/results/f7-sweep-v1.json, f7-sweep-v2.json, f7-ablation.json and
f7-eval.json (whichever exist) and writes docs/media/F7-envelope.png and docs/ops/F7-operations-report.md.

    envs/mj/bin/python -I factory/ops/f7_report.py
"""
import json, os, sys
from collections import Counter
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
RES = os.path.join(HERE, "results"); FIG = os.path.join(ROOT, "docs", "media", "F7-envelope.png"); REPORT = os.path.join(ROOT, "docs", "ops", "F7-operations-report.md")
LOSSES = ("missed", "late", "dropped", "knocked_off", "wrong_chute")


def load(n):
    p = os.path.join(RES, n); return json.load(open(p)) if os.path.exists(p) else None


def figure(v1, v2, abl):
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 3, figsize=(16, 4.8)); fig.suptitle("F7: the sorting cell's operating envelope, v1 (F5 cell) and v2 (fast belt changes)", fontsize=12)
    cols = {0.15: "#2f855a", 0.3: "#2b6cb0", 0.5: "#c53030"}
    for S, ls, tag in ((v1, "--", "v1"), (v2, "-", "v2")):
        if not S: continue
        for sp in sorted({r["speed"] for r in S["rows"]}):
            rr = sorted([r for r in S["rows"] if r["speed"] == sp and r["clutter"] == 0.25], key=lambda r: r["rate"])
            ax[0].plot([r["rate"] for r in rr], [r["sorted_per_min"] for r in rr], ls, marker="o", color=cols.get(sp, "k"), label=f"{tag} {sp:g} m/s")
    ax[0].set_xlabel("arrivals per minute (25% in touching pairs)"); ax[0].set_ylabel("sorted per minute"); ax[0].set_title("throughput vs load", fontsize=10); ax[0].legend(fontsize=7, ncol=2)
    # losses split by class at 12/min, clutter 0.25
    bars = []
    for S, tag in ((v1, "v1"), (v2, "v2")):
        if not S: continue
        for sp in (0.15, 0.3, 0.5):
            r = next((r for r in S["rows"] if r["speed"] == sp and r["rate"] == 12.0 and r["clutter"] == 0.25), None)
            if r: bars.append((f"{tag}\n{sp:g}", r["outcomes"]))
    lc = {"sorted": "#2f855a", "missed": "#a0aec0", "late": "#ecc94b", "dropped": "#dd6b20", "knocked_off": "#9f7aea", "wrong_chute": "#c53030"}
    for i, (lab, oc) in enumerate(bars):
        tot = sum(oc.values()) or 1; b = 0
        for k in ("sorted",) + LOSSES:
            v = 100 * oc.get(k, 0) / tot; ax[1].bar(i, v, bottom=b, color=lc[k], label=k if i == 0 else None); b += v
    ax[1].set_xticks(range(len(bars)), [b[0] for b in bars], fontsize=8); ax[1].set_ylabel("% of items"); ax[1].set_title("where items go (12/min, 25% pairs): losses by class", fontsize=10)
    ax[1].legend(fontsize=7, loc="lower right")
    if abl:
        keys = [k for k in abl["table"]]; sp_keys = sorted({abl["table"][k]["speed"] for k in keys})
        names = []
        for k in keys:
            n = "+".join(abl["table"][k]["v2"]) or "v1"
            if n not in names: names.append(n)
        w = 0.8 / len(sp_keys)
        for j, sp in enumerate(sp_keys):
            vals = [next((abl["table"][k]["sorted_per_min"] for k in keys if abl["table"][k]["speed"] == sp and ("+".join(abl["table"][k]["v2"]) or "v1") == n), 0) for n in names]
            ax[2].bar(np.arange(len(names)) + (j - (len(sp_keys) - 1) / 2) * w, vals, w, color=cols.get(sp, "k"), label=f"{sp:g} m/s")
        ax[2].set_xticks(range(len(names)), [n.replace("+", "\n+") for n in names], fontsize=7); ax[2].set_ylabel("sorted per minute")
        ax[2].set_title(f"each change alone (F5 stream, {abl['seeds'][1] - abl['seeds'][0] + 1} seeds x 180 s)", fontsize=10); ax[2].legend(fontsize=8)
    fig.tight_layout(); os.makedirs(os.path.dirname(FIG), exist_ok=True); fig.savefig(FIG, dpi=105); plt.close(fig)


def envelope_table(S):
    if not S: return "(not run)\n"
    out = ["| belt m/s | arrivals/min | pairs | sorted/min | sort rate | " + " | ".join(LOSSES) + " | protective stops |", "|---" * (6 + len(LOSSES)) + "|"]
    for r in S["rows"]:
        out.append(f"| {r['speed']:g} | {r['rate']:g} | {r['clutter']:.0%} | {r['sorted_per_min']} | {r['sort_rate']} | " + " | ".join(str(r["outcomes"].get(k, 0)) for k in LOSSES) + f" | {r['protective_stops']} |")
    return "\n".join(out) + "\n"


def report(v1, v2, abl, ev):
    L = ["# Operations report: the fast belt (F7), 2026-11-03", "",
         "Generated by `factory/ops/f7_report.py` from recorded runs (simulation). The v1 cell is the F5 cell (vision only, the student",
         "carry, the hybrid gripper, the lookahead scheduler); v2 adds the F7 changes (`line.V2_FLAGS`: fast, early, deadline).", "",
         "![the envelope](../media/F7-envelope.png)", ""]
    L += [f"## The v1 envelope ({v1['seeds']} seeds x {v1['seconds']:.0f} s per row, seeds from {v1['seed0']})" if v1 else "## The v1 envelope", "", envelope_table(v1)]
    if v1: L += ["At 0.5 m/s the v1 cell sorts nothing: every item is missed. Its approach (joint limits 2.4 / 3.0 rad/s, the intercept searched from 0.6 s after the decision in 0.35 s steps) is too slow for an item that crosses the 1.1 m reach window in 2.2 s: the planner's pre-grasp pose is already out of reach when the tool could get there (in a probe, 108 pre-grasp IK failures and 0 attempts in 40 s).", ""]
    L += [f"## The v2 envelope" + (f" ({v2['seeds']} seeds x {v2['seconds']:.0f} s per row, seeds from {v2['seed0']})" if v2 else ""), "", envelope_table(v2)]
    if abl:
        L += ["## Each change on its own (F5 stream: 12 arrivals/min, 25% touching pairs)", "", "| speed · variant | sorted/min | sort rate | attempt success | cycle s | protective stops | wrong chutes |", "|---|---|---|---|---|---|---|"]
        for k, r in abl["table"].items(): L.append(f"| {k} | {r['sorted_per_min']} | {r['sort_rate']} | {r['attempt_success']} | {r['cycle_s']} | {r['protective_stops']} | {r['wrong_chute']} |")
        L += ["", "Paired differences against v1 on the same seeds (sorted/min, mean [95% CI]):", ""]
        for v, d in abl["vs_v1"].items(): L.append(f"- {v}: " + "; ".join(f"{sp} m/s {x['mean']:+.2f} [{x['lo']:+.2f}, {x['hi']:+.2f}]" for sp, x in d.items()))
        L.append("")
    if ev:
        L += ["## Acceptance (pre-registered, `factory/ops/results/f7-eval-protocol.md`)", "", f"Rule: {ev['rule']} (margin {ev['margin']} sorted/min). Seeds {ev['seeds'][0]}-{ev['seeds'][1]}, {ev['seconds']:.0f} s each.", ""]
        for sp, d in ev["paired"].items(): L.append(f"- {sp} m/s: v2 - v1 = {d['mean']:+.2f} sorted/min [{d['lo']:+.2f}, {d['hi']:+.2f}] (n = {d['n']})")
        L += ["", f"Verdict: {json.dumps(ev['verdict'])}", ""]
    open(REPORT, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    v1, v2, abl, ev = load("f7-sweep-v1.json"), load("f7-sweep-v2.json"), load("f7-ablation.json"), load("f7-eval.json")
    figure(v1, v2, abl); report(v1, v2, abl, ev); print(FIG); print(REPORT)
